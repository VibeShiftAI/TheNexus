#!/usr/bin/env bash
# Attribute the dashboard `npm test` failures retained by task 91f1f758 (Nexus menu)
# to the menu change or to its QA baseline. Follow-up task 68909e82, 2026-10-21.
#
# Runs the dashboard suite (the `npm test` command line) in throwaway detached git
# worktrees under /tmp, never in the working tree:
#   baseline            c193147, the QA baseline of task 91f1f758
#   baseline-plus-menu  baseline + the menu's suite-visible files as committed at e3230af
#   head-without-menu   HEAD with those files put back to the baseline (so the pair also
#                       isolates any later menu change, such as 68909e82's footer fix)
#   head                HEAD
#   control-old-assert  HEAD with only ready-for-review.test.mjs put back to the baseline:
#                       a negative control showing that a text assertion on nav-sidebar.tsx
#                       left un-updated fails, and is attributed to the menu
# then writes outcomes-<run>.tsv (every test), failures-<run>.txt (TAP of each failure)
# and attribution-table.md. Worktrees, not archives: nexus-barrel.test.ts walks git
# history. The sibling nexus-shared repo and the installed node_modules are linked in,
# as the working tree sees them.
#
#   bash docs/reviews/2026-10-20-nexus-menu/followup/attribute-suite-failures.sh [out-dir]
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(git -C "$HERE" rev-parse --show-toplevel)
OUT=${1:-$HERE}
BASE=c193147
MENU=e3230af
HEAD_SHA=$(git -C "$REPO" rev-parse --short HEAD)
RUNS=(baseline baseline-plus-menu head-without-menu head control-old-assert)
# The menu files the suite can see. The browser check (dashboard/scripts/) is not in the
# suite's globs, so it cannot affect `npm test`.
MENU_FILES=(
    dashboard/src/components/nav-sidebar.tsx
    dashboard/src/components/__tests__/nav-sidebar-menu.test.mjs
    dashboard/src/components/__tests__/ready-for-review.test.mjs
)
WORK=$(mktemp -d /tmp/nav-attr.XXXXXX)
cleanup() {
    for r in "${RUNS[@]}"; do
        [ -d "$WORK/$r" ] && git -C "$REPO" worktree remove --force "$WORK/$r" >/dev/null 2>&1 || true
    done
    git -C "$REPO" worktree prune
    rm -rf "$WORK"
}
trap cleanup EXIT
mkdir -p "$OUT"
# daily-journal-tabs.test.ts reads ../nexus-shared relative to the repo.
ln -s "$(cd "$REPO/.." && pwd)/nexus-shared" "$WORK/nexus-shared"

stage() {
    git -C "$REPO" worktree add --detach --quiet "$WORK/$1" "$2"
    ln -s "$REPO/node_modules" "$WORK/$1/node_modules"
    ln -s "$REPO/dashboard/node_modules" "$WORK/$1/dashboard/node_modules"
}
# put <run> <rev> <path>: the file as it is at <rev>, or no file when <rev> lacks it.
put() {
    if git -C "$REPO" cat-file -e "$2:$3" 2>/dev/null; then
        git -C "$REPO" show "$2:$3" > "$WORK/$1/$3"
    else
        rm -f "$WORK/$1/$3"
    fi
}
run() {
    local status=0
    (cd "$WORK/$1/dashboard" && node --import ./test/register.mjs --test \
        --test-reporter=tap --test-reporter-destination="$WORK/$1.tap" \
        --test-reporter="$HERE/outcome-reporter.mjs" --test-reporter-destination="$OUT/outcomes-$1.tsv" \
        "src/**/__tests__/*.test.mjs" "src/**/__tests__/*.test.ts" "test/*.test.mjs") || status=$?
    node "$HERE/suite-outcomes.mjs" failures "$WORK/$1.tap" > "$OUT/failures-$1.txt"
    echo "$1: exit $status, $(grep -E '^# (tests|pass|fail) ' "$WORK/$1.tap" | tr '\n' ' ')"
}

echo "baseline $BASE, menu $MENU, HEAD $HEAD_SHA, node $(node --version)"
echo "commits touching the menu files since the baseline:"
git -C "$REPO" log --format='  %h %s' "$BASE..$HEAD_SHA" -- "${MENU_FILES[@]}"
stage baseline "$BASE"
stage baseline-plus-menu "$BASE"
for f in "${MENU_FILES[@]}"; do put baseline-plus-menu "$MENU" "$f"; done
stage head-without-menu "$HEAD_SHA"
for f in "${MENU_FILES[@]}"; do put head-without-menu "$BASE" "$f"; done
stage head "$HEAD_SHA"
stage control-old-assert "$HEAD_SHA"
put control-old-assert "$BASE" dashboard/src/components/__tests__/ready-for-review.test.mjs

# One at a time, so runs do not compete for CPU and change timing-sensitive tests.
for r in "${RUNS[@]}"; do run "$r"; done

{
    echo "Generated by attribute-suite-failures.sh: baseline $BASE, menu $MENU, HEAD $HEAD_SHA, node $(node --version)."
    echo
    node "$HERE/suite-outcomes.mjs" compare $(for r in "${RUNS[@]}"; do printf '%s=%s ' "$r" "$OUT/outcomes-$r.tsv"; done)
} > "$OUT/attribution-table.md"
echo "wrote $OUT/attribution-table.md"
